// Format date from YYYY-MM-DD to Turkish format
function formatDate(dateString) {
    const date = new Date(dateString);
    const months = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 
                   'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık'];
    return `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
}

// Get category badge class
function getCategoryBadgeClass(category) {
    if (category === 'Ulaşım İpuçları') {
        return 'bg-primary';
    }
    return 'bg-secondary';
}

// Load and render blog posts
function loadBlogPosts() {
    try {
        const posts = blogPostsData;
        
        const blogContainer = document.getElementById('blog-posts-container');
        if (!blogContainer) return;
        
        blogContainer.innerHTML = '';
        
        posts.forEach(post => {
            const postCard = document.createElement('div');
            postCard.className = 'col-md-6 col-lg-4 mb-4';
            
            postCard.innerHTML = `
                <div class="card blog-card h-100">
                    <div class="card-body">
                        <span class="badge ${getCategoryBadgeClass(post.category)} mb-2">${post.category}</span>
                        <h5 class="card-title">${post.title}</h5>
                        <p class="card-text">${post.summary}</p>
                        <p class="blog-meta"><i class="bi bi-calendar"></i> ${formatDate(post.date)}</p>
                        <a href="blog-${post.slug}.html" class="btn btn-outline-primary">Devamını Oku</a>
                    </div>
                </div>
            `;
            
            blogContainer.appendChild(postCard);
        });
    } catch (error) {
        console.error('Blog yüklenirken hata:', error);
        const blogContainer = document.getElementById('blog-posts-container');
        if (blogContainer) {
            blogContainer.innerHTML = '<div class="col-12"><p class="text-center text-muted">Blog yazıları yüklenirken bir hata oluştu.</p></div>';
        }
    }
}

// Load single blog post content
function loadBlogPost(slug) {
    try {
        const posts = blogPostsData;
        
        const post = posts.find(p => p.slug === slug);
        if (!post) {
            console.error('Blog yazısı bulunamadı:', slug);
            return;
        }
        
        // Update page title
        document.title = `${post.title} | Çerkezköy Bağlık Taksi Blog`;
        
        // Update meta description
        const metaDescription = document.querySelector('meta[name="description"]');
        if (metaDescription) {
            metaDescription.content = post.summary;
        }
        
        // Update breadcrumb
        const breadcrumbActive = document.querySelector('.breadcrumb-item.active');
        if (breadcrumbActive) {
            breadcrumbActive.textContent = post.title;
        }
        
        // Update header
        const headerTitle = document.querySelector('article header h1');
        if (headerTitle) {
            headerTitle.textContent = post.title;
        }
        
        // Update badge
        const badge = document.querySelector('article header .badge');
        if (badge) {
            badge.className = `badge ${getCategoryBadgeClass(post.category)} mb-2`;
            badge.textContent = post.category;
        }
        
        // Update date
        const dateElement = document.querySelector('article header .text-muted span');
        if (dateElement) {
            dateElement.textContent = formatDate(post.date);
        }
        
        // Update content
        const contentContainer = document.querySelector('.blog-content');
        if (contentContainer) {
            // Convert markdown-like content to HTML
            let htmlContent = post.content;
            
            // Split by double newlines to get blocks
            const blocks = htmlContent.split(/\n\n+/);
            let finalHtml = '';
            let inList = false;
            let firstPara = true;
            
            blocks.forEach(block => {
                block = block.trim();
                if (!block) return;
                
                const lines = block.split('\n');
                let blockHtml = '';
                
                lines.forEach((line, index) => {
                    line = line.trim();
                    if (!line) return;
                    
                    // Check for headings
                    if (line.startsWith('## ')) {
                        if (inList) {
                            blockHtml += '</ul>';
                            inList = false;
                        }
                        blockHtml += `<h2 class="mt-5 mb-3">${line.substring(3).trim()}</h2>`;
                    } else if (line.startsWith('### ')) {
                        if (inList) {
                            blockHtml += '</ul>';
                            inList = false;
                        }
                        blockHtml += `<h3 class="mt-4 mb-3">${line.substring(4).trim()}</h3>`;
                    } else if (line.startsWith('- ')) {
                        // List item
                        if (!inList) {
                            blockHtml += '<ul>';
                            inList = true;
                        }
                        blockHtml += `<li>${line.substring(2).trim()}</li>`;
                    } else {
                        // Regular paragraph
                        if (inList) {
                            blockHtml += '</ul>';
                            inList = false;
                        }
                        if (firstPara) {
                            blockHtml += `<p class="lead">${line}</p>`;
                            firstPara = false;
                        } else {
                            blockHtml += `<p>${line}</p>`;
                        }
                    }
                });
                
                if (inList) {
                    blockHtml += '</ul>';
                    inList = false;
                }
                
                finalHtml += blockHtml;
            });
            
            // Add contact info at the end
            finalHtml += `
                <div class="mt-5 p-4 bg-light rounded">
                    <h3 class="mb-3">İletişim ve Rezervasyon</h3>
                    <p>Rezervasyon yapmak isterseniz, bize telefon ile ulaşabilirsiniz:</p>
                    <p class="alert alert-info">
                        <strong><i class="bi bi-telephone"></i> Telefon:</strong> <a href="tel:+905438922662" class="phone-link">0 543 892 26 62</a><br>
                        <strong>Hizmet:</strong> 7/24 Kesintisiz
                    </p>
                </div>
            `;
            
            contentContainer.innerHTML = finalHtml;
        }
        
    } catch (error) {
        console.error('Blog yazısı yüklenirken hata:', error);
    }
}

// Initialize blog functionality
document.addEventListener('DOMContentLoaded', function() {
    // Check if we're on blog listing page
    if (document.getElementById('blog-posts-container')) {
        loadBlogPosts();
    }
    
    // Check if we're on a blog post detail page
    const currentPath = window.location.pathname;
    const blogPostMatch = currentPath.match(/blog-([^/]+)\.html/);
    if (blogPostMatch) {
        const slug = blogPostMatch[1];
        loadBlogPost(slug);
    }
});

